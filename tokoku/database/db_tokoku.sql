-- READ-ONLY schema inspection for the existing db_tokoku database.
-- This file intentionally does not create, drop, or alter application objects.

SELECT TABLE_NAME, TABLE_TYPE
FROM information_schema.TABLES
WHERE TABLE_SCHEMA = 'db_tokoku'
ORDER BY TABLE_TYPE, TABLE_NAME;

SELECT TABLE_NAME, COLUMN_NAME, COLUMN_TYPE, IS_NULLABLE
FROM information_schema.COLUMNS
WHERE TABLE_SCHEMA = 'db_tokoku'
ORDER BY TABLE_NAME, ORDINAL_POSITION;

SELECT ROUTINE_TYPE, ROUTINE_NAME, DTD_IDENTIFIER
FROM information_schema.ROUTINES
WHERE ROUTINE_SCHEMA = 'db_tokoku'
ORDER BY ROUTINE_TYPE, ROUTINE_NAME;

SELECT TRIGGER_NAME, EVENT_MANIPULATION, ACTION_TIMING, EVENT_OBJECT_TABLE
FROM information_schema.TRIGGERS
WHERE TRIGGER_SCHEMA = 'db_tokoku'
ORDER BY TRIGGER_NAME;
